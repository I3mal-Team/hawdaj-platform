<?php

namespace App\Models;

use App\Observers\PlaceObserver;
use App\Traits\HasImage;
use App\Traits\HasPlaceTranslationUpdate;
use Astrotomic\Translatable\Contracts\Translatable as TranslatableContract;
use Astrotomic\Translatable\Translatable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;
use Spatie\MediaLibrary\HasMedia;
use Spatie\MediaLibrary\InteractsWithMedia;
use Spatie\MediaLibrary\MediaCollections\Models\Media;

class Place extends Model implements TranslatableContract, HasMedia
{
    use SoftDeletes, HasFactory, HasImage, Translatable, HasPlaceTranslationUpdate, InteractsWithMedia;

    protected $guarded = [];
    public array $translatedAttributes = ['title', 'description'];
    protected $with = ['translations'];
    public const TYPE_PLACE = 'Place';

    protected static function boot()
    {
        parent::boot(); // TODO: Change the autogenerated stub
        static::observe(PlaceObserver::class);
    }

    protected $casts = [
        // 'seasons' => 'array',
        'key_words' => 'array',
        'categories' => 'array',
        'lat' => 'float',
        'long' => 'float',
        'user_id' => 'int',
        'related_places' => 'array',
        'near_stores' => 'array',
        'featured' => 'boolean',
        'visited' => 'boolean',
    ];

    public $appends = [
        'rate',
        'review',
        'type',
        // 'distance'
    ];

    public function getTypeAttribute()
    {
        return 'place';
    }

